-- заявка на подтверждение через Telegram: приложение создаёт, бот заполняет
create table if not exists public.phone_links (
  token       uuid primary key default gen_random_uuid(),
  user_id     uuid not null,
  chat_id     bigint,
  status      text not null default 'pending' check (status in ('pending','done','login','failed')),
  phone       text,
  login_hash  text,          -- одноразовый ключ входа в уже существующий профиль с этим номером
  message     text,
  created_at  timestamptz not null default now()
);
create index if not exists phone_links_chat_idx on public.phone_links (chat_id, created_at desc);
alter table public.phone_links enable row level security;   -- доступ только у серверной функции

-- звонок-сброс: храним только хэш кода
create table if not exists public.phone_calls (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null,
  phone       text not null,
  code_hash   text not null,
  attempts    int not null default 0,
  expires_at  timestamptz not null,
  created_at  timestamptz not null default now()
);
create index if not exists phone_calls_user_idx on public.phone_calls (user_id, created_at desc);
create index if not exists phone_calls_phone_idx on public.phone_calls (phone, created_at desc);
alter table public.phone_calls enable row level security;

-- кому принадлежит номер (последние 10 цифр)
create or replace function public.find_user_by_phone(p_phone text) returns uuid
language sql stable security definer set search_path = public, auth as $$
  select id from auth.users
   where phone is not null and right(phone, 10) = right(regexp_replace(p_phone, '\D', '', 'g'), 10)
   order by phone_confirmed_at desc nulls last limit 1;
$$;

-- перенос накопленного на устройстве (адреса, заказы, имя, согласия) в существующий профиль
create or replace function public.merge_guest(p_from uuid, p_to uuid) returns void
language plpgsql security definer set search_path = public as $$
declare src public.profiles;
begin
  if p_from is null or p_to is null or p_from = p_to then return; end if;
  update public.addresses set user_id = p_to where user_id = p_from;
  update public.orders    set user_id = p_to where user_id = p_from;
  select * into src from public.profiles where id = p_from;
  if found then
    insert into public.profiles (id, name, phone, birthday, pd_consent_version, pd_consent_at, marketing_consent, marketing_consent_at)
    values (p_to, src.name, src.phone, src.birthday, src.pd_consent_version, src.pd_consent_at, src.marketing_consent, src.marketing_consent_at)
    on conflict (id) do update set
      name     = case when public.profiles.name = '' then excluded.name else public.profiles.name end,
      birthday = coalesce(public.profiles.birthday, excluded.birthday),
      pd_consent_version = coalesce(excluded.pd_consent_version, public.profiles.pd_consent_version),
      pd_consent_at      = coalesce(excluded.pd_consent_at, public.profiles.pd_consent_at),
      marketing_consent  = public.profiles.marketing_consent or excluded.marketing_consent,
      marketing_consent_at = coalesce(excluded.marketing_consent_at, public.profiles.marketing_consent_at);
    delete from public.profiles where id = p_from;
  end if;
  update public.consent_log set user_id = p_to where user_id = p_from;
end $$;

revoke execute on function public.find_user_by_phone(text) from public, anon, authenticated;
revoke execute on function public.merge_guest(uuid, uuid)  from public, anon, authenticated;
grant execute on function public.find_user_by_phone(text), public.merge_guest(uuid, uuid) to service_role;

-- уборка старых заявок
create or replace function public.verify_cleanup() returns void
language sql security definer set search_path = public as $$
  delete from public.phone_links where created_at < now() - interval '1 day';
  delete from public.phone_calls where created_at < now() - interval '1 day';
$$;
grant execute on function public.verify_cleanup() to service_role;
