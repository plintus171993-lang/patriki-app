-- ============================================================
-- Патрики Паб — обновление 008: своя программа лояльности («карта гостя»)
--  • правила (уровни по сумме покупок, % начисления, лимит списания, бонусы) — в админке, таблица loyalty_settings
--  • баллы за заказы в приложении (после статуса «Доставлен») и за чек в заведении по QR-коду
--  • списание баллов при заказе в приложении и на кассе
--  • API для кассы (iiko): pos_lookup / pos_accrue по ключу из app_secrets.pos_api_key
-- 1 балл = 1 ₽. Можно запускать повторно.
-- ============================================================

create table if not exists public.loyalty_settings (
  id               int primary key default 1 check (id = 1),
  enabled          boolean not null default true,
  verified_only    boolean not null default true,   -- копят только гости с подтверждённым номером
  app_enabled      boolean not null default true,   -- начислять за заказы в приложении
  venue_enabled    boolean not null default true,   -- начислять в заведении по QR
  tiers            jsonb   not null default '[{"name":"Гость","from":0,"pct":5},{"name":"Завсегдатай","from":5000,"pct":10},{"name":"Свой человек","from":15000,"pct":15}]',
  period_days      int     not null default 0,      -- уровень по покупкам за N дней (0 — за всё время)
  app_min_order    int     not null default 0,      -- минимальная сумма заказа в приложении для начисления
  accrue_delivery  boolean not null default false,  -- начислять ли на стоимость доставки
  max_redeem_pct   int     not null default 30 check (max_redeem_pct between 0 and 90),
  burn_after_days  int     not null default 0,      -- баллы сгорают, если не было покупок N дней (0 — не сгорают)
  welcome_bonus    int     not null default 0,
  birthday_bonus   int     not null default 0,
  rules_text       text    not null default '',
  updated_at       timestamptz not null default now()
);
insert into public.loyalty_settings (id) values (1) on conflict do nothing;

create table if not exists public.loyalty_accounts (
  user_id          uuid primary key references auth.users(id) on delete cascade,
  card_no          text not null unique,
  secret           text not null default replace(gen_random_uuid()::text, '-', ''),
  balance          int  not null default 0 check (balance >= 0),
  spent_total      int  not null default 0,
  welcome_given    boolean not null default false,
  birthday_year    int,
  last_activity_at timestamptz not null default now(),
  created_at       timestamptz not null default now()
);

create table if not exists public.loyalty_tx (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users(id) on delete cascade,
  kind        text not null check (kind in ('accrue','redeem','refund','bonus','adjust','expire','reverse')),
  points      int  not null,                 -- со знаком: + начислено, − списано
  amount      int  not null default 0,       -- сумма покупки, от которой считали
  pct         int,
  source      text not null default 'app' check (source in ('app','venue','pos','admin','system')),
  venue_id    text references public.venues(id) on delete set null,
  order_id    uuid references public.orders(id) on delete set null,
  ext_id      text,                          -- номер чека кассы (защита от двойного начисления)
  staff_id    uuid,
  note        text not null default '',
  created_at  timestamptz not null default now()
);
create index if not exists loyalty_tx_user_idx on public.loyalty_tx (user_id, created_at desc);
create unique index if not exists loyalty_tx_ext_idx on public.loyalty_tx (source, ext_id) where ext_id is not null;
create unique index if not exists loyalty_tx_order_kind_idx on public.loyalty_tx (order_id, kind) where order_id is not null and kind in ('accrue','redeem');

alter table public.orders add column if not exists points_redeemed int not null default 0;

alter table public.loyalty_settings enable row level security;
alter table public.loyalty_accounts enable row level security;
alter table public.loyalty_tx       enable row level security;
drop policy if exists "loyalty settings read"  on public.loyalty_settings;
drop policy if exists "loyalty settings owner" on public.loyalty_settings;
create policy "loyalty settings read"  on public.loyalty_settings for select to anon, authenticated using (true);
create policy "loyalty settings owner" on public.loyalty_settings for update to authenticated using (public.is_owner()) with check (public.is_owner());
drop policy if exists "loyalty acc own" on public.loyalty_accounts;
create policy "loyalty acc own" on public.loyalty_accounts for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists "loyalty tx own" on public.loyalty_tx;
create policy "loyalty tx own" on public.loyalty_tx for select to authenticated using (user_id = auth.uid() or public.is_admin());

-- ---------- вспомогательное ----------
create or replace function public.loyalty_cfg() returns public.loyalty_settings
language sql stable security definer set search_path = public as $$ select * from public.loyalty_settings where id = 1 $$;

-- сумма покупок для уровня
create or replace function public.loyalty_spent(p_user uuid) returns int
language plpgsql stable security definer set search_path = public as $$
declare c public.loyalty_settings := public.loyalty_cfg(); s int;
begin
  if c.period_days > 0 then
    select coalesce(sum(case when kind = 'reverse' then -amount else amount end), 0) into s
      from public.loyalty_tx where user_id = p_user and kind in ('accrue','reverse') and created_at > now() - make_interval(days => c.period_days);
  else
    select spent_total into s from public.loyalty_accounts where user_id = p_user;
  end if;
  return coalesce(s, 0);
end $$;

-- уровень по сумме: { name, from, pct, next_name, next_from }
create or replace function public.loyalty_tier(p_spent int) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare c public.loyalty_settings := public.loyalty_cfg(); t jsonb; cur jsonb := null; nxt jsonb := null;
begin
  for t in select value from jsonb_array_elements(c.tiers) order by (value->>'from')::int loop
    if p_spent >= (t->>'from')::int then cur := t; elsif nxt is null then nxt := t; end if;
  end loop;
  if cur is null then cur := '{"name":"Гость","from":0,"pct":0}'; end if;
  return cur || jsonb_build_object('next_name', nxt->>'name', 'next_from', (nxt->>'from')::int);
end $$;

create or replace function public.loyalty_verified(p_user uuid) returns boolean
language sql stable security definer set search_path = public, auth as $$
  select coalesce((select phone is not null and phone <> '' and phone_confirmed_at is not null from auth.users where id = p_user), false);
$$;

-- счёт гостя (создаётся при первом обращении); ленивые бонусы и сгорание
create or replace function public.loyalty_account(p_user uuid) returns public.loyalty_accounts
language plpgsql security definer set search_path = public as $$
declare a public.loyalty_accounts; c public.loyalty_settings := public.loyalty_cfg(); bd date; no text; i int := 0;
begin
  select * into a from public.loyalty_accounts where user_id = p_user for update;
  if not found then
    loop
      no := lpad((floor(random() * 90000000) + 10000000)::bigint::text, 8, '0');
      begin
        insert into public.loyalty_accounts (user_id, card_no) values (p_user, no) returning * into a;
        exit;
      exception when unique_violation then i := i + 1; if i > 20 then raise; end if;
      end;
    end loop;
  end if;
  if not c.enabled or (c.verified_only and not public.loyalty_verified(p_user)) then return a; end if;

  if c.burn_after_days > 0 and a.balance > 0 and a.last_activity_at < now() - make_interval(days => c.burn_after_days) then
    insert into public.loyalty_tx (user_id, kind, points, source, note) values (p_user, 'expire', -a.balance, 'system', 'Сгорели: давно не было покупок');
    update public.loyalty_accounts set balance = 0 where user_id = p_user returning * into a;
  end if;
  if c.welcome_bonus > 0 and not a.welcome_given then
    insert into public.loyalty_tx (user_id, kind, points, source, note) values (p_user, 'bonus', c.welcome_bonus, 'system', 'Приветственные баллы');
    update public.loyalty_accounts set balance = balance + c.welcome_bonus, welcome_given = true where user_id = p_user returning * into a;
  end if;
  select birthday into bd from public.profiles where id = p_user;
  if c.birthday_bonus > 0 and bd is not null and coalesce(a.birthday_year, 0) < extract(year from now())::int
     and abs(extract(doy from now()) - extract(doy from make_date(extract(year from now())::int, extract(month from bd)::int, least(extract(day from bd)::int, 28)))) <= 3 then
    insert into public.loyalty_tx (user_id, kind, points, source, note) values (p_user, 'bonus', c.birthday_bonus, 'system', 'С днём рождения!');
    update public.loyalty_accounts set balance = balance + c.birthday_bonus, birthday_year = extract(year from now())::int where user_id = p_user returning * into a;
  end if;
  return a;
end $$;

-- начисление (общая логика для приложения, заведения и кассы)
create or replace function public.loyalty_add(p_user uuid, p_amount int, p_source text, p_venue text, p_order uuid, p_ext text, p_staff uuid, p_note text default '')
returns int language plpgsql security definer set search_path = public as $$
declare c public.loyalty_settings := public.loyalty_cfg(); a public.loyalty_accounts; t jsonb; pts int;
begin
  if not c.enabled or p_amount <= 0 then return 0; end if;
  if c.verified_only and not public.loyalty_verified(p_user) then return 0; end if;
  a := public.loyalty_account(p_user);
  t := public.loyalty_tier(public.loyalty_spent(p_user));      -- процент по уровню ДО этой покупки
  pts := floor(p_amount * (t->>'pct')::numeric / 100);
  insert into public.loyalty_tx (user_id, kind, points, amount, pct, source, venue_id, order_id, ext_id, staff_id, note)
  values (p_user, 'accrue', pts, p_amount, (t->>'pct')::int, p_source, p_venue, p_order, p_ext, p_staff, coalesce(p_note, ''));
  update public.loyalty_accounts set balance = balance + pts, spent_total = spent_total + p_amount, last_activity_at = now() where user_id = p_user;
  return pts;
end $$;

-- ---------- для гостя ----------
create or replace function public.my_loyalty() returns jsonb
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); a public.loyalty_accounts; c public.loyalty_settings := public.loyalty_cfg(); sp int; hist jsonb;
begin
  if me is null then raise exception 'Нет сессии'; end if;
  a := public.loyalty_account(me);
  sp := public.loyalty_spent(me);
  select coalesce(jsonb_agg(h order by h.created_at desc), '[]') into hist from (
    select t.kind, t.points, t.amount, t.pct, t.source, t.note, t.created_at, v.name as venue
    from public.loyalty_tx t left join public.venues v on v.id = t.venue_id
    where t.user_id = me order by t.created_at desc limit 30) h;
  return jsonb_build_object(
    'card_no', a.card_no, 'secret', a.secret, 'balance', a.balance, 'spent', sp,
    'tier', public.loyalty_tier(sp), 'verified', public.loyalty_verified(me), 'history', hist,
    'settings', jsonb_build_object('enabled', c.enabled, 'verified_only', c.verified_only, 'tiers', c.tiers, 'period_days', c.period_days,
      'max_redeem_pct', c.max_redeem_pct, 'app_enabled', c.app_enabled, 'venue_enabled', c.venue_enabled, 'app_min_order', c.app_min_order,
      'burn_after_days', c.burn_after_days, 'welcome_bonus', c.welcome_bonus, 'birthday_bonus', c.birthday_bonus, 'rules_text', c.rules_text));
end $$;
grant execute on function public.my_loyalty() to authenticated;

-- ---------- QR-код гостя: PK1:<карта>:<код>, код меняется каждые 30 секунд ----------
create or replace function public.loyalty_otp(p_secret text, p_window bigint) returns text
language sql immutable as $$
  select lpad(((('x' || substr(encode(sha256(convert_to(p_secret || ':' || p_window, 'UTF8')), 'hex'), 1, 8))::bit(32)::bigint) % 1000000)::text, 6, '0');
$$;

-- найти гостя по QR, номеру карты или телефону
create or replace function public.loyalty_find(p_code text) returns uuid
language plpgsql stable security definer set search_path = public, auth as $$
declare s text := trim(coalesce(p_code, '')); parts text[]; a public.loyalty_accounts; w bigint := floor(extract(epoch from now()) / 30); d text;
begin
  if s like 'PK1:%' then
    parts := string_to_array(s, ':');
    select * into a from public.loyalty_accounts where card_no = parts[2];
    if not found then return null; end if;
    if parts[3] in (public.loyalty_otp(a.secret, w), public.loyalty_otp(a.secret, w - 1), public.loyalty_otp(a.secret, w - 2), public.loyalty_otp(a.secret, w + 1)) then
      return a.user_id;
    end if;
    raise exception 'QR-код устарел — попросите гостя открыть карту заново';
  end if;
  d := regexp_replace(s, '\D', '', 'g');
  if length(d) = 8 then select user_id into a.user_id from public.loyalty_accounts where card_no = d; return a.user_id; end if;
  if length(d) >= 10 then
    return (select id from auth.users where phone is not null and right(phone, 10) = right(d, 10) and phone_confirmed_at is not null limit 1);
  end if;
  return null;
end $$;

create or replace function public.loyalty_card_info(p_user uuid) returns jsonb
language plpgsql security definer set search_path = public, auth as $$
declare a public.loyalty_accounts; sp int; nm text; ph text; c public.loyalty_settings := public.loyalty_cfg();
begin
  a := public.loyalty_account(p_user); sp := public.loyalty_spent(p_user);
  select name into nm from public.profiles where id = p_user;
  select phone into ph from auth.users where id = p_user;
  return jsonb_build_object('card_no', a.card_no, 'name', coalesce(nullif(nm, ''), 'Гость'), 'phone_last4', right(coalesce(ph, ''), 4),
    'balance', a.balance, 'tier', public.loyalty_tier(sp), 'max_redeem_pct', c.max_redeem_pct,
    'active', c.enabled and (not c.verified_only or public.loyalty_verified(p_user)));
end $$;

-- общая операция «чек в заведении»: списать баллы и начислить на остаток
create or replace function public.loyalty_check(p_user uuid, p_amount int, p_redeem int, p_venue text, p_source text, p_ext text, p_staff uuid, p_note text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare c public.loyalty_settings := public.loyalty_cfg(); a public.loyalty_accounts; red int := greatest(coalesce(p_redeem, 0), 0); pts int; old public.loyalty_tx;
begin
  if p_ext is not null then
    select * into old from public.loyalty_tx where source = p_source and ext_id = p_ext and kind = 'accrue';
    if found then return jsonb_build_object('duplicate', true, 'points', old.points) || public.loyalty_card_info(p_user); end if;
  end if;
  if not c.enabled or not c.venue_enabled then raise exception 'Начисление в заведении выключено в настройках'; end if;
  if c.verified_only and not public.loyalty_verified(p_user) then raise exception 'У гостя не подтверждён номер — баллы не копятся'; end if;
  if coalesce(p_amount, 0) <= 0 then raise exception 'Укажите сумму чека'; end if;
  a := public.loyalty_account(p_user);
  if red > a.balance then raise exception 'У гостя только % баллов', a.balance; end if;
  if red > floor(p_amount * c.max_redeem_pct / 100.0) then raise exception 'Баллами можно оплатить не больше % %% чека', c.max_redeem_pct; end if;
  if red > 0 then
    insert into public.loyalty_tx (user_id, kind, points, amount, source, venue_id, ext_id, staff_id, note)
    values (p_user, 'redeem', -red, p_amount, p_source, p_venue, case when p_ext is null then null else p_ext || ':r' end, p_staff, coalesce(p_note, ''));
    update public.loyalty_accounts set balance = balance - red, last_activity_at = now() where user_id = p_user;
  end if;
  pts := public.loyalty_add(p_user, p_amount - red, p_source, p_venue, null, p_ext, p_staff, p_note);
  return jsonb_build_object('points', pts, 'redeemed', red) || public.loyalty_card_info(p_user);
end $$;

-- ---------- касса в админке (управляющий / бармен) ----------
create or replace function public.staff_lookup(p_code text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid;
begin
  if not public.is_admin() then raise exception 'Нет прав'; end if;
  u := public.loyalty_find(p_code);
  if u is null then raise exception 'Гость не найден'; end if;
  return public.loyalty_card_info(u) || jsonb_build_object('code', p_code);
end $$;

create or replace function public.staff_accrue(p_code text, p_amount int, p_redeem int, p_venue text, p_note text default '')
returns jsonb language plpgsql security definer set search_path = public as $$
declare u uuid;
begin
  if not public.can_manage(p_venue) then raise exception 'Нет доступа к этому заведению'; end if;
  u := public.loyalty_find(p_code);
  if u is null then raise exception 'Гость не найден'; end if;
  return public.loyalty_check(u, p_amount, p_redeem, p_venue, 'venue', null, auth.uid(), p_note);
end $$;
grant execute on function public.staff_lookup(text), public.staff_accrue(text, int, int, text, text) to authenticated;

-- ---------- API для кассы iiko (по ключу) ----------
create or replace function public.pos_key_ok(p_key text) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(p_key, '') <> '' and exists (select 1 from public.app_secrets where key = 'pos_api_key' and value = p_key);
$$;
create or replace function public.pos_lookup(p_key text, p_code text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid;
begin
  if not public.pos_key_ok(p_key) then raise exception 'Неверный ключ кассы'; end if;
  u := public.loyalty_find(p_code);
  if u is null then raise exception 'Гость не найден'; end if;
  return public.loyalty_card_info(u);
end $$;
create or replace function public.pos_accrue(p_key text, p_code text, p_amount int, p_redeem int, p_venue text, p_check_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare u uuid;
begin
  if not public.pos_key_ok(p_key) then raise exception 'Неверный ключ кассы'; end if;
  if coalesce(p_check_id, '') = '' then raise exception 'Нужен номер чека'; end if;
  u := public.loyalty_find(p_code);
  if u is null then raise exception 'Гость не найден'; end if;
  return public.loyalty_check(u, p_amount, p_redeem, p_venue, 'pos', p_check_id, null, 'Касса');
end $$;
grant execute on function public.pos_lookup(text, text), public.pos_accrue(text, text, int, int, text, text) to anon, authenticated;

-- ---------- заказы в приложении ----------
-- оформление: + списание баллов (p_order.redeem)
create or replace function public.place_order(p_order jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v        public.venues;
  line     jsonb;
  it       public.items;
  qty      int;
  lines    jsonb := '[]'::jsonb;
  subtotal int := 0;
  o        public.orders;
  digits   text := regexp_replace(coalesce(p_order->>'phone',''), '\D', '', 'g');
  verified boolean := false;
  pay      text := coalesce(p_order->>'payment', 'card');
  consent  text := left(coalesce(p_order->>'pd_consent', ''), 40);
  red      int := greatest(coalesce((p_order->>'redeem')::int, 0), 0);
  c        public.loyalty_settings := public.loyalty_cfg();
  acc      public.loyalty_accounts;
begin
  if consent = '' then raise exception 'Нужно согласие на обработку персональных данных'; end if;
  select * into v from public.venues where id = p_order->>'venue_id';
  if not found then raise exception 'Неизвестное заведение'; end if;
  if not v.accepting then raise exception 'Заведение сейчас не принимает заказы'; end if;
  if pay not in ('card','cash','online') then pay := 'card'; end if;
  if pay = 'online' and not v.pay_online then raise exception 'Онлайн-оплата недоступна'; end if;

  if length(coalesce(trim(p_order->>'customer_name'),'')) not between 1 and 80 then raise exception 'Имя'; end if;
  if length(digits) not between 10 and 12 then raise exception 'Телефон'; end if;
  if length(coalesce(trim(p_order->>'address'),'')) not between 3 and 300 then raise exception 'Адрес'; end if;
  if jsonb_typeof(p_order->'items') <> 'array' or jsonb_array_length(p_order->'items') not between 1 and 60 then raise exception 'Состав заказа'; end if;

  for line in select * from jsonb_array_elements(p_order->'items') loop
    qty := least(greatest(coalesce((line->>'qty')::int, 0), 0), 50);
    continue when qty = 0;
    select * into it from public.items where id = line->>'item_id' and available and not (v.id = any(stop_in));
    continue when not found;
    lines := lines || jsonb_build_object('item_id', it.id, 'name', it.name, 'price', it.price, 'qty', qty);
    subtotal := subtotal + it.price * qty;
  end loop;

  if jsonb_array_length(lines) = 0 then raise exception 'Позиции недоступны'; end if;
  if subtotal < v.min_order then raise exception 'Меньше минимального заказа'; end if;

  if auth.uid() is not null then
    select (u.phone_confirmed_at is not null and right(u.phone, 10) = right(digits, 10))
      into verified from auth.users u where u.id = auth.uid();
  end if;

  if red > 0 then
    if auth.uid() is null or not c.enabled or (c.verified_only and not public.loyalty_verified(auth.uid())) then raise exception 'Баллы недоступны'; end if;
    acc := public.loyalty_account(auth.uid());
    if red > acc.balance then raise exception 'Недостаточно баллов'; end if;
    if red > floor(subtotal * c.max_redeem_pct / 100.0) then raise exception 'Баллами можно оплатить не больше % %%', c.max_redeem_pct; end if;
  end if;

  insert into public.orders (venue_id, customer_name, phone, address, comment, when_text, payment, payment_status,
                             items, subtotal, delivery_fee, total, user_id, phone_verified, pd_consent_version, points_redeemed)
  values (
    v.id, left(trim(p_order->>'customer_name'), 80), left(trim(p_order->>'phone'), 30), left(trim(p_order->>'address'), 300),
    left(coalesce(p_order->>'comment', ''), 500), left(coalesce(p_order->>'when_text', ''), 50),
    pay, case when pay = 'online' then 'pending' else 'none' end,
    lines, subtotal, v.delivery_fee, subtotal + v.delivery_fee - red, auth.uid(), coalesce(verified, false), consent, red
  ) returning * into o;

  if red > 0 then
    insert into public.loyalty_tx (user_id, kind, points, amount, source, venue_id, order_id, note)
    values (auth.uid(), 'redeem', -red, subtotal, 'app', v.id, o.id, 'Оплата заказа №' || o.number);
    update public.loyalty_accounts set balance = balance - red, last_activity_at = now() where user_id = auth.uid();
  end if;

  return jsonb_build_object('id', o.id, 'number', o.number, 'total', o.total);
end $$;

-- статус заказа → начисление после доставки, возврат баллов при отмене
create or replace function public.orders_loyalty() returns trigger
language plpgsql security definer set search_path = public as $$
declare c public.loyalty_settings := public.loyalty_cfg(); base int; acc public.loyalty_tx;
begin
  if new.user_id is null or new.status is not distinct from old.status then return new; end if;
  if new.status = 'done' and c.enabled and c.app_enabled then
    base := new.subtotal - new.points_redeemed + case when c.accrue_delivery then new.delivery_fee else 0 end;
    if base >= greatest(c.app_min_order, 1) and not exists (select 1 from public.loyalty_tx where order_id = new.id and kind = 'accrue') then
      perform public.loyalty_add(new.user_id, base, 'app', new.venue_id, new.id, null, null, 'Заказ №' || new.number);
    end if;
  elsif new.status = 'cancelled' then
    if new.points_redeemed > 0 and not exists (select 1 from public.loyalty_tx where order_id = new.id and kind = 'refund') then
      insert into public.loyalty_tx (user_id, kind, points, source, venue_id, order_id, note)
      values (new.user_id, 'refund', new.points_redeemed, 'app', new.venue_id, new.id, 'Возврат баллов: заказ №' || new.number || ' отменён');
      update public.loyalty_accounts set balance = balance + new.points_redeemed where user_id = new.user_id;
    end if;
    select * into acc from public.loyalty_tx where order_id = new.id and kind = 'accrue';
    if found and not exists (select 1 from public.loyalty_tx where order_id = new.id and kind = 'reverse') then
      insert into public.loyalty_tx (user_id, kind, points, amount, source, venue_id, order_id, note)
      values (new.user_id, 'reverse', -least(acc.points, (select balance from public.loyalty_accounts where user_id = new.user_id)), acc.amount, 'app', new.venue_id, new.id, 'Отмена начисления: заказ №' || new.number);
      update public.loyalty_accounts set balance = greatest(balance - acc.points, 0), spent_total = greatest(spent_total - acc.amount, 0) where user_id = new.user_id;
    end if;
  end if;
  return new;
end $$;
drop trigger if exists orders_loyalty on public.orders;
create trigger orders_loyalty after update of status on public.orders for each row execute function public.orders_loyalty();

