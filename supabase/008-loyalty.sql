-- сводка для владельца
create or replace function public.loyalty_stats() returns jsonb
language sql stable security definer set search_path = public as $$
  select case when public.is_admin() then jsonb_build_object(
    'guests', (select count(*) from public.loyalty_accounts where spent_total > 0 or balance > 0),
    'balance', (select coalesce(sum(balance), 0) from public.loyalty_accounts),
    'accrued_30', (select coalesce(sum(points), 0) from public.loyalty_tx where kind in ('accrue','bonus') and created_at > now() - interval '30 days'),
    'redeemed_30', (select coalesce(-sum(points), 0) from public.loyalty_tx where kind = 'redeem' and created_at > now() - interval '30 days'))
  else null end;
$$;
grant execute on function public.loyalty_stats() to authenticated;

