-- =====================================================================
--  Обновление 013: «Связь с руководством» и «Отзывы гостей»
--  • feedback — обращения (жалоба / предложение / благодарность) и отзывы с оценкой
--  • обращения уходят в Telegram-группу учредителей (app_secrets: telegram_chat_id:founders),
--    ответ — реплаем на сообщение бота в группе, гость видит его в приложении («Мои обращения»)
--  • отзывы видны в приложении после публикации владельцем (public_reviews)
--  Обращения видит только владелец (is_owner); отзывы — и управляющие заведения (can_manage).
-- =====================================================================

create table if not exists public.feedback (
  id          uuid primary key default gen_random_uuid(),
  number      bigint generated by default as identity (start with 1001) unique,
  user_id     uuid default auth.uid(),
  kind        text not null check (kind in ('complaint','idea','thanks','review')),
  venue_id    text references public.venues(id),
  rating      int check (rating between 1 and 5),
  text        text not null default '',
  name        text not null default '',
  phone       text not null default '',
  order_number bigint,
  wants_call  boolean not null default false,
  status      text not null default 'new' check (status in ('new','answered','closed')),
  reply       text,
  replied_at  timestamptz,
  published   boolean not null default false,
  created_at  timestamptz not null default now()
);
create index if not exists feedback_created on public.feedback (created_at desc);
alter table public.feedback enable row level security;
drop policy if exists "feedback own read" on public.feedback;
create policy "feedback own read" on public.feedback for select to authenticated using (user_id = auth.uid());
drop policy if exists "feedback admin read" on public.feedback;
create policy "feedback admin read" on public.feedback for select to authenticated
  using (public.is_owner() or (kind = 'review' and venue_id is not null and public.can_manage(venue_id)));

-- текст для Telegram
create or replace function public.feedback_tg_text(f public.feedback) returns text
language sql stable security definer set search_path = public as $$
  select format(E'%s №%s\n📍 %s\n%s%s\n\n%s\n\n👤 %s%s%s%s',
    case f.kind when 'complaint' then '🔴 Обращение (жалоба)' when 'idea' then '💡 Обращение (предложение)'
                when 'thanks' then '🙏 Обращение (благодарность)' else '⭐ Отзыв' end,
    f.number,
    coalesce((select name from public.venues where id = f.venue_id), 'заведение не указано'),
    case when f.rating is not null then repeat('★', f.rating) || repeat('☆', 5 - f.rating) else '' end,
    case when f.order_number is not null then E'\nЗаказ №' || f.order_number else '' end,
    f.text,
    coalesce(nullif(f.name, ''), 'Гость'),
    case when f.phone <> '' then ', ' || f.phone else '' end,
    case when f.wants_call then E'\n📞 Просит перезвонить' else '' end,
    case when f.kind <> 'review' then E'\n\n↩️ Ответьте на это сообщение (Reply) — гость увидит ответ в приложении.' else '' end);
$$;

create or replace function public.feedback_notify(f public.feedback) returns void
language plpgsql security definer set search_path = public as $$
declare founders text; venue_chat text; msg text;
begin
  select value into founders from public.app_secrets where key = 'telegram_chat_id:founders';
  if founders is null then select value into founders from public.app_secrets where key = 'telegram_chat_id'; end if;
  msg := public.feedback_tg_text(f);
  if founders is not null then perform public.tg_send(founders, msg); end if;
  -- отзыв дублируем в тему заведения, чтобы его видела смена
  if f.kind = 'review' and f.venue_id is not null then
    select value into venue_chat from public.app_secrets where key = 'telegram_chat_id:' || f.venue_id;
    if venue_chat is not null and venue_chat is distinct from founders then perform public.tg_send(venue_chat, msg); end if;
  end if;
exception when others then null;
end $$;

-- гость отправляет обращение или отзыв
create or replace function public.submit_feedback(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare f public.feedback; k text; t text; r int; ph text;
begin
  if auth.uid() is null then raise exception 'Нет входа'; end if;
  k := coalesce(p->>'kind', '');
  if k not in ('complaint','idea','thanks','review') then raise exception 'Выберите тему обращения'; end if;
  t := left(trim(coalesce(p->>'text', '')), 2000);
  r := nullif(p->>'rating', '')::int;
  if k = 'review' and (r is null or r < 1 or r > 5) then raise exception 'Поставьте оценку от 1 до 5'; end if;
  if k <> 'review' and length(t) < 5 then raise exception 'Опишите, пожалуйста, что случилось'; end if;
  ph := regexp_replace(coalesce(p->>'phone', ''), '\D', '', 'g');
  if (coalesce((p->>'wants_call')::boolean, false) or ph <> '') and coalesce((p->>'pd_consent')::boolean, false) is not true then
    raise exception 'Нужно согласие на обработку персональных данных';
  end if;
  if (select count(*) from public.feedback where user_id = auth.uid() and created_at > now() - interval '1 hour') >= 5 then
    raise exception 'Слишком много сообщений подряд. Попробуйте позже или позвоните в паб';
  end if;
  insert into public.feedback (kind, venue_id, rating, text, name, phone, order_number, wants_call)
  values (k, nullif(p->>'venue_id', ''), r, t, left(trim(coalesce(p->>'name', '')), 80),
          case when length(ph) >= 11 then '+' || ph else '' end,
          nullif(regexp_replace(coalesce(p->>'order_number', ''), '\D', '', 'g'), '')::bigint,
          coalesce((p->>'wants_call')::boolean, false) and length(ph) >= 11)
  returning * into f;
  perform public.feedback_notify(f);
  return jsonb_build_object('id', f.id, 'number', f.number);
end $$;

-- ответ из Telegram (вызывает функция verify от service_role) или из админки
create or replace function public.feedback_reply(p_number bigint, p_reply text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare f public.feedback;
begin
  if current_user not in ('service_role', 'postgres') and not public.is_owner() then raise exception 'Нет прав'; end if;
  update public.feedback set reply = left(trim(p_reply), 2000), replied_at = now(), status = 'answered'
   where number = p_number returning * into f;
  if not found then raise exception 'Обращение не найдено'; end if;
  return jsonb_build_object('number', f.number, 'kind', f.kind, 'name', f.name);
end $$;

create or replace function public.set_feedback(p_id uuid, p_status text default null, p_published boolean default null) returns void
language plpgsql security definer set search_path = public as $$
declare f public.feedback;
begin
  select * into f from public.feedback where id = p_id for update;
  if not found then raise exception 'Не найдено'; end if;
  if not (public.is_owner() or (f.kind = 'review' and f.venue_id is not null and public.can_manage(f.venue_id))) then raise exception 'Нет прав'; end if;
  if p_status is not null and p_status not in ('new','answered','closed') then raise exception 'Неверный статус'; end if;
  if p_published is true and f.kind <> 'review' then raise exception 'Публикуются только отзывы'; end if;
  update public.feedback set status = coalesce(p_status, status), published = coalesce(p_published, published) where id = p_id;
end $$;

-- опубликованные отзывы для всех: только имя, оценка, текст, ответ паба
create or replace function public.public_reviews(p_limit int default 30) returns table (
  id uuid, venue_id text, rating int, text text, name text, reply text, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select f.id, f.venue_id, f.rating, f.text, coalesce(nullif(split_part(trim(f.name), ' ', 1), ''), 'Гость'), f.reply, f.created_at
    from public.feedback f
   where f.kind = 'review' and f.published
   order by f.created_at desc
   limit least(greatest(p_limit, 1), 100);
$$;

grant execute on function public.submit_feedback(jsonb), public.set_feedback(uuid, text, boolean), public.feedback_reply(bigint, text) to authenticated;
grant execute on function public.public_reviews(int) to anon, authenticated;
revoke execute on function public.feedback_notify(public.feedback) from public, anon, authenticated;
