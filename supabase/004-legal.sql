alter table public.orders add column if not exists pd_consent_version text;

-- ---------- журнал согласий (доказательство для проверки: кто, когда, на что, отозвал ли) ----------
create table if not exists public.consent_log (
  id          bigint generated by default as identity primary key,
  user_id     uuid,
  phone       text not null default '',
  kind        text not null check (kind in ('pd','marketing')),
  granted     boolean not null,
  version     text not null default '',
  source      text not null default '',      -- checkout / verify / profile / delete
  created_at  timestamptz not null default now()
);
alter table public.consent_log enable row level security;
drop policy if exists "consent admin read" on public.consent_log;
create policy "consent admin read" on public.consent_log for select to authenticated using (public.is_admin());
-- запись только через функцию ниже

create or replace function public.record_consent(p_kind text, p_granted boolean, p_version text, p_source text)
returns void language plpgsql security definer set search_path = public as $$
declare ph text;
begin
  if auth.uid() is null then raise exception 'Нет сессии'; end if;
  if p_kind not in ('pd','marketing') then raise exception 'Вид согласия'; end if;
  select coalesce(nullif(u.phone,''), (select p.phone from public.profiles p where p.id = auth.uid()), '')
    into ph from auth.users u where u.id = auth.uid();
  insert into public.consent_log (user_id, phone, kind, granted, version, source)
  values (auth.uid(), coalesce(ph,''), p_kind, p_granted, left(coalesce(p_version,''), 40), left(coalesce(p_source,''), 40));

  insert into public.profiles (id) values (auth.uid()) on conflict (id) do nothing;
  if p_kind = 'pd' then
    update public.profiles set pd_consent_version = case when p_granted then left(p_version, 40) end,
                               pd_consent_at = case when p_granted then now() end
     where id = auth.uid();
  else
    update public.profiles set marketing_consent = p_granted, marketing_consent_at = now() where id = auth.uid();
  end if;
end $$;
grant execute on function public.record_consent(text, boolean, text, text) to authenticated;

-- ---------- оформление заказа: без согласия на обработку ПД заказ не принимается ----------
create or replace function public.place_order(p_order jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v        public.venues;
  line     jsonb;
  it       public.items;
  qty      int;
  lines    jsonb := '[]'::jsonb;
  subtotal int := 0;
  o        public.orders;
  digits   text := regexp_replace(coalesce(p_order->>'phone',''), '\D', '', 'g');
  verified boolean := false;
  pay      text := coalesce(p_order->>'payment', 'card');
  consent  text := left(coalesce(p_order->>'pd_consent', ''), 40);
begin
  if consent = '' then raise exception 'Нужно согласие на обработку персональных данных'; end if;
  select * into v from public.venues where id = p_order->>'venue_id';
  if not found then raise exception 'Неизвестное заведение'; end if;
  if not v.accepting then raise exception 'Заведение сейчас не принимает заказы'; end if;
  if pay not in ('card','cash','online') then pay := 'card'; end if;
  if pay = 'online' and not v.pay_online then raise exception 'Онлайн-оплата недоступна'; end if;

  if length(coalesce(trim(p_order->>'customer_name'),'')) not between 1 and 80 then raise exception 'Имя'; end if;
  if length(digits) not between 10 and 12 then raise exception 'Телефон'; end if;
  if length(coalesce(trim(p_order->>'address'),'')) not between 3 and 300 then raise exception 'Адрес'; end if;
  if jsonb_typeof(p_order->'items') <> 'array' or jsonb_array_length(p_order->'items') not between 1 and 60 then raise exception 'Состав заказа'; end if;

  for line in select * from jsonb_array_elements(p_order->'items') loop
    qty := least(greatest(coalesce((line->>'qty')::int, 0), 0), 50);
    continue when qty = 0;
    select * into it from public.items where id = line->>'item_id' and available;
    continue when not found;
    lines := lines || jsonb_build_object('item_id', it.id, 'name', it.name, 'price', it.price, 'qty', qty);
    subtotal := subtotal + it.price * qty;
  end loop;

  if jsonb_array_length(lines) = 0 then raise exception 'Позиции недоступны'; end if;
  if subtotal < v.min_order then raise exception 'Меньше минимального заказа'; end if;

  if auth.uid() is not null then
    select (u.phone_confirmed_at is not null and right(u.phone, 10) = right(digits, 10))
      into verified from auth.users u where u.id = auth.uid();
  end if;

  insert into public.orders (venue_id, customer_name, phone, address, comment, when_text, payment, payment_status,
                             items, subtotal, delivery_fee, total, user_id, phone_verified, pd_consent_version)
  values (
    v.id, left(trim(p_order->>'customer_name'), 80), left(trim(p_order->>'phone'), 30), left(trim(p_order->>'address'), 300),
    left(coalesce(p_order->>'comment', ''), 500), left(coalesce(p_order->>'when_text', ''), 50),
    pay, case when pay = 'online' then 'pending' else 'none' end,
    lines, subtotal, v.delivery_fee, subtotal + v.delivery_fee, auth.uid(), coalesce(verified, false), consent
  ) returning * into o;

  return jsonb_build_object('id', o.id, 'number', o.number, 'total', o.total);
end $$;

-- ---------- удаление профиля гостем ----------
-- Удаляем профиль, адреса, коды входа; в заказах стираем имя, телефон и адрес
-- (суммы и состав остаются — они нужны для бухгалтерского учёта, 402-ФЗ).
-- Незавершённый заказ — сначала дождаться доставки.
create or replace function public.delete_my_account() returns jsonb
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); ph text;
begin
  if me is null then raise exception 'Нет сессии'; end if;
  if exists (select 1 from public.orders where user_id = me and status in ('new','cooking','delivering')
             and not (payment = 'online' and payment_status in ('pending','failed'))) then
    raise exception 'ACTIVE_ORDER';
  end if;
  select right(coalesce(phone,''), 10) into ph from auth.users where id = me;

  insert into public.consent_log (user_id, phone, kind, granted, version, source)
  values (me, '', 'pd', false, '', 'delete'), (me, '', 'marketing', false, '', 'delete');

  update public.orders set customer_name = 'Профиль удалён', phone = '', address = 'удалено', comment = ''
   where user_id = me;
  update public.orders set user_id = null where user_id = me;
  delete from public.addresses where user_id = me;
  delete from public.profiles  where id = me;
  delete from public.guest_transfers where from_user = me;
  if coalesce(ph,'') <> '' then delete from public.sms_outbox where right(phone, 10) = ph; end if;

  begin
    delete from auth.users where id = me;
  exception when others then
    -- нет прав на auth.users — хотя бы отвязываем номер
    begin update auth.users set phone = null, phone_confirmed_at = null where id = me; exception when others then null; end;
  end;
  return jsonb_build_object('ok', true);
end $$;
grant execute on function public.delete_my_account() to authenticated;
