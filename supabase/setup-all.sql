-- оформление: + списание баллов (p_order.redeem)
create or replace function public.place_order(p_order jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v        public.venues;
  line     jsonb;
  it       public.items;
  qty      int;
  lines    jsonb := '[]'::jsonb;
  subtotal int := 0;
  o        public.orders;
  digits   text := regexp_replace(coalesce(p_order->>'phone',''), '\D', '', 'g');
  verified boolean := false;
  pay      text := coalesce(p_order->>'payment', 'card');
  consent  text := left(coalesce(p_order->>'pd_consent', ''), 40);
  red      int := greatest(coalesce((p_order->>'redeem')::int, 0), 0);
  c        public.loyalty_settings := public.loyalty_cfg();
  acc      public.loyalty_accounts;
begin
  if consent = '' then raise exception 'Нужно согласие на обработку персональных данных'; end if;
  select * into v from public.venues where id = p_order->>'venue_id';
  if not found then raise exception 'Неизвестное заведение'; end if;
  if not v.accepting then raise exception 'Заведение сейчас не принимает заказы'; end if;
  if pay not in ('card','cash','online') then pay := 'card'; end if;
  if pay = 'online' and not v.pay_online then raise exception 'Онлайн-оплата недоступна'; end if;

  if length(coalesce(trim(p_order->>'customer_name'),'')) not between 1 and 80 then raise exception 'Имя'; end if;
  if length(digits) not between 10 and 12 then raise exception 'Телефон'; end if;
  if length(coalesce(trim(p_order->>'address'),'')) not between 3 and 300 then raise exception 'Адрес'; end if;
  if jsonb_typeof(p_order->'items') <> 'array' or jsonb_array_length(p_order->'items') not between 1 and 60 then raise exception 'Состав заказа'; end if;

  for line in select * from jsonb_array_elements(p_order->'items') loop
    qty := least(greatest(coalesce((line->>'qty')::int, 0), 0), 50);
    continue when qty = 0;
    select * into it from public.items where id = line->>'item_id' and available and not (v.id = any(stop_in));
    continue when not found;
    lines := lines || jsonb_build_object('item_id', it.id, 'name', it.name, 'price', it.price, 'qty', qty);
    subtotal := subtotal + it.price * qty;
  end loop;

  if jsonb_array_length(lines) = 0 then raise exception 'Позиции недоступны'; end if;
  if subtotal < v.min_order then raise exception 'Меньше минимального заказа'; end if;

  if auth.uid() is not null then
    select (u.phone_confirmed_at is not null and right(u.phone, 10) = right(digits, 10))
      into verified from auth.users u where u.id = auth.uid();
  end if;

  if red > 0 then
    if auth.uid() is null or not c.enabled or (c.verified_only and not public.loyalty_verified(auth.uid())) then raise exception 'Баллы недоступны'; end if;
    acc := public.loyalty_account(auth.uid());
    if red > acc.balance then raise exception 'Недостаточно баллов'; end if;
    if red > floor(subtotal * c.max_redeem_pct / 100.0) then raise exception 'Баллами можно оплатить не больше % %%', c.max_redeem_pct; end if;
  end if;

  insert into public.orders (venue_id, customer_name, phone, address, comment, when_text, payment, payment_status,
                             items, subtotal, delivery_fee, total, user_id, phone_verified, pd_consent_version, points_redeemed)
  values (
    v.id, left(trim(p_order->>'customer_name'), 80), left(trim(p_order->>'phone'), 30), left(trim(p_order->>'address'), 300),
    left(coalesce(p_order->>'comment', ''), 500), left(coalesce(p_order->>'when_text', ''), 50),
    pay, case when pay = 'online' then 'pending' else 'none' end,
    lines, subtotal, v.delivery_fee, subtotal + v.delivery_fee - red, auth.uid(), coalesce(verified, false), consent, red
  ) returning * into o;

  if red > 0 then
    insert into public.loyalty_tx (user_id, kind, points, amount, source, venue_id, order_id, note)
    values (auth.uid(), 'redeem', -red, subtotal, 'app', v.id, o.id, 'Оплата заказа №' || o.number);
    update public.loyalty_accounts set balance = balance - red, last_activity_at = now() where user_id = auth.uid();
  end if;

  return jsonb_build_object('id', o.id, 'number', o.number, 'total', o.total);
end $$;

-- статус заказа → начисление после доставки, возврат баллов при отмене
create or replace function public.orders_loyalty() returns trigger
language plpgsql security definer set search_path = public as $$
declare c public.loyalty_settings := public.loyalty_cfg(); base int; acc public.loyalty_tx;
begin
  if new.user_id is null or new.status is not distinct from old.status then return new; end if;
  if new.status = 'done' and c.enabled and c.app_enabled then
    base := new.subtotal - new.points_redeemed + case when c.accrue_delivery then new.delivery_fee else 0 end;
    if base >= greatest(c.app_min_order, 1) and not exists (select 1 from public.loyalty_tx where order_id = new.id and kind = 'accrue') then
      perform public.loyalty_add(new.user_id, base, 'app', new.venue_id, new.id, null, null, 'Заказ №' || new.number);
    end if;
  elsif new.status = 'cancelled' then
    if new.points_redeemed > 0 and not exists (select 1 from public.loyalty_tx where order_id = new.id and kind = 'refund') then
      insert into public.loyalty_tx (user_id, kind, points, source, venue_id, order_id, note)
      values (new.user_id, 'refund', new.points_redeemed, 'app', new.venue_id, new.id, 'Возврат баллов: заказ №' || new.number || ' отменён');
      update public.loyalty_accounts set balance = balance + new.points_redeemed where user_id = new.user_id;
    end if;
    select * into acc from public.loyalty_tx where order_id = new.id and kind = 'accrue';
    if found and not exists (select 1 from public.loyalty_tx where order_id = new.id and kind = 'reverse') then
      insert into public.loyalty_tx (user_id, kind, points, amount, source, venue_id, order_id, note)
      values (new.user_id, 'reverse', -least(acc.points, (select balance from public.loyalty_accounts where user_id = new.user_id)), acc.amount, 'app', new.venue_id, new.id, 'Отмена начисления: заказ №' || new.number);
      update public.loyalty_accounts set balance = greatest(balance - acc.points, 0), spent_total = greatest(spent_total - acc.amount, 0) where user_id = new.user_id;
    end if;
  end if;
  return new;
end $$;
