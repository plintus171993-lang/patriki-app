create or replace function public.record_consent(p_kind text, p_granted boolean, p_version text, p_source text)
returns void language plpgsql security definer set search_path = public as $$
declare ph text;
begin
  if auth.uid() is null then raise exception 'Нет сессии'; end if;
  if p_kind not in ('pd','marketing') then raise exception 'Вид согласия'; end if;
  select coalesce(nullif(u.phone,''), (select p.phone from public.profiles p where p.id = auth.uid()), '')
    into ph from auth.users u where u.id = auth.uid();
  insert into public.consent_log (user_id, phone, kind, granted, version, source)
  values (auth.uid(), coalesce(ph,''), p_kind, p_granted, left(coalesce(p_version,''), 40), left(coalesce(p_source,''), 40));

  insert into public.profiles (id) values (auth.uid()) on conflict (id) do nothing;
  if p_kind = 'pd' then
    update public.profiles set pd_consent_version = case when p_granted then left(p_version, 40) end,
                               pd_consent_at = case when p_granted then now() end
     where id = auth.uid();
