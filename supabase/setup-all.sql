create extension if not exists pg_net;

-- ---------- таблицы ----------
create table if not exists public.categories (
  id    text primary key,
  name  text not null,
  sort  int  not null default 0
);

create table if not exists public.items (
  id           text primary key default gen_random_uuid()::text,
  category_id  text not null references public.categories(id) on delete cascade,
  name         text not null,
  price        int  not null check (price > 0),
  weight       text not null default '',
  description  text not null default '',
  image_url    text not null default '',
  available    boolean not null default true,
  popular      boolean not null default false,
  sort         int not null default 0,
  updated_at   timestamptz not null default now()
);

create table if not exists public.venues (
  id            text primary key,
  name          text not null,
  address       text not null default '',
  zone          text not null default '',
  phone         text not null default '',
  hours         text not null default '',
  delivery_fee  int  not null default 0 check (delivery_fee >= 0),
  min_order     int  not null default 0 check (min_order >= 0),
  eta_minutes   int  not null default 45,
  accepting     boolean not null default true,
  sort          int not null default 0
);

create table if not exists public.orders (
  id             uuid primary key default gen_random_uuid(),
  number         bigint generated by default as identity (start with 1001) unique,
  venue_id       text not null references public.venues(id),
  customer_name  text not null,
  phone          text not null,
  address        text not null,
  comment        text not null default '',
  when_text      text not null default '',
  payment        text not null check (payment in ('card','cash')),
  items          jsonb not null,
  subtotal       int not null,
  delivery_fee   int not null default 0,
  total          int not null,
  status         text not null default 'new' check (status in ('new','cooking','delivering','done','cancelled')),
  created_at     timestamptz not null default now()
);
create index if not exists orders_created_idx on public.orders (created_at desc);

-- Кто управляющий: строка с его user_id из auth.users
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

-- Секреты (токен Telegram-бота). Доступа из приложения нет вообще.
create table if not exists public.app_secrets (
  key   text primary key,
  value text not null
);

-- ---------- права ----------
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

alter table public.categories  enable row level security;
alter table public.items       enable row level security;
alter table public.venues      enable row level security;
alter table public.orders      enable row level security;
alter table public.admins      enable row level security;
alter table public.app_secrets enable row level security;

-- меню и заведения: читают все, меняет только управляющий
do $$
declare t text;
begin
  foreach t in array array['categories','items','venues'] loop
    execute format('drop policy if exists "%1$s read" on public.%1$s', t);
    execute format('drop policy if exists "%1$s admin write" on public.%1$s', t);
    execute format('create policy "%1$s read" on public.%1$s for select to anon, authenticated using (true)', t);
    execute format('create policy "%1$s admin write" on public.%1$s for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;

-- заказы: гости создают только через place_order(), видит и меняет только управляющий
drop policy if exists "orders admin read" on public.orders;
drop policy if exists "orders admin update" on public.orders;
create policy "orders admin read"   on public.orders for select to authenticated using (public.is_admin());
create policy "orders admin update" on public.orders for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- ---------- оформление заказа (цены считает сервер) ----------
create or replace function public.place_order(p_order jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v        public.venues;
  line     jsonb;
  it       public.items;
  qty      int;
  lines    jsonb := '[]'::jsonb;
  subtotal int := 0;
  o        public.orders;
begin
  select * into v from public.venues where id = p_order->>'venue_id';
  if not found then raise exception 'Неизвестное заведение'; end if;
  if not v.accepting then raise exception 'Заведение сейчас не принимает заказы'; end if;

  if length(coalesce(trim(p_order->>'customer_name'),'')) not between 1 and 80 then raise exception 'Имя'; end if;
  if length(regexp_replace(coalesce(p_order->>'phone',''), '\D', '', 'g')) not between 10 and 12 then raise exception 'Телефон'; end if;
  if length(coalesce(trim(p_order->>'address'),'')) not between 3 and 300 then raise exception 'Адрес'; end if;
  if jsonb_typeof(p_order->'items') <> 'array' or jsonb_array_length(p_order->'items') not between 1 and 60 then raise exception 'Состав заказа'; end if;

  for line in select * from jsonb_array_elements(p_order->'items') loop
    qty := least(greatest(coalesce((line->>'qty')::int, 0), 0), 50);
    continue when qty = 0;
    select * into it from public.items where id = line->>'item_id' and available;
    continue when not found;
    lines := lines || jsonb_build_object('item_id', it.id, 'name', it.name, 'price', it.price, 'qty', qty);
    subtotal := subtotal + it.price * qty;
  end loop;

  if jsonb_array_length(lines) = 0 then raise exception 'Позиции недоступны'; end if;
  if subtotal < v.min_order then raise exception 'Меньше минимального заказа'; end if;

  insert into public.orders (venue_id, customer_name, phone, address, comment, when_text, payment, items, subtotal, delivery_fee, total)
  values (
    v.id, left(trim(p_order->>'customer_name'), 80), left(trim(p_order->>'phone'), 30), left(trim(p_order->>'address'), 300),
    left(coalesce(p_order->>'comment', ''), 500), left(coalesce(p_order->>'when_text', ''), 50),
    case when p_order->>'payment' = 'cash' then 'cash' else 'card' end,
    lines, subtotal, v.delivery_fee, subtotal + v.delivery_fee
  ) returning * into o;

  return jsonb_build_object('id', o.id, 'number', o.number, 'total', o.total);
end $$;

-- статус заказа для гостя (знает только тот, у кого есть id заказа)
create or replace function public.order_status(p_id uuid) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('status', status, 'number', number) from public.orders where id = p_id;
$$;

grant execute on function public.place_order(jsonb) to anon, authenticated;
grant execute on function public.order_status(uuid) to anon, authenticated;
grant execute on function public.is_admin() to anon, authenticated;

-- ---------- уведомление в Telegram о новом заказе ----------
create or replace function public.notify_telegram() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  token text; chat text; msg text; venue_name text; line jsonb;
begin
  select value into token from public.app_secrets where key = 'telegram_bot_token';
  select value into chat  from public.app_secrets where key = 'telegram_chat_id';
  if token is null or chat is null then return new; end if;

  select name into venue_name from public.venues where id = new.venue_id;
  msg := format(E'🍖 Новый заказ №%s — %s\n%s\n\n', new.number, coalesce(venue_name, new.venue_id), new.when_text);
  for line in select * from jsonb_array_elements(new.items) loop
    msg := msg || format(E'• %s × %s = %s ₽\n', line->>'name', line->>'qty', (line->>'price')::int * (line->>'qty')::int);
  end loop;
  msg := msg || format(E'\nИтого: %s ₽ (%s)\n%s, %s\n%s',
    new.total, case new.payment when 'cash' then 'наличные' else 'карта курьеру' end,
    new.customer_name, new.phone, new.address);
  if new.comment <> '' then msg := msg || E'\nКомментарий: ' || new.comment; end if;

  perform net.http_post(
    url     := 'https://api.telegram.org/bot' || token || '/sendMessage',
    body    := jsonb_build_object('chat_id', chat, 'text', msg),
    headers := '{"Content-Type": "application/json"}'::jsonb
  );
  return new;
exception when others then
  return new; -- заказ не теряем, даже если Telegram недоступен
end $$;

drop trigger if exists orders_notify_telegram on public.orders;
create trigger orders_notify_telegram after insert on public.orders
  for each row execute function public.notify_telegram();

