create or replace function public.delete_my_account() returns jsonb
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); ph text;
begin
  if me is null then raise exception 'Нет сессии'; end if;
  if exists (select 1 from public.orders where user_id = me and status in ('new','cooking','delivering')
             and not (payment = 'online' and payment_status in ('pending','failed'))) then
    raise exception 'ACTIVE_ORDER';
  end if;
  select right(coalesce(phone,''), 10) into ph from auth.users where id = me;

  insert into public.consent_log (user_id, phone, kind, granted, version, source)
  values (me, '', 'pd', false, '', 'delete'), (me, '', 'marketing', false, '', 'delete');

  update public.orders set customer_name = 'Профиль удалён', phone = '', address = 'удалено', comment = ''
   where user_id = me;
  update public.orders set user_id = null where user_id = me;
  delete from public.addresses where user_id = me;
  delete from public.profiles  where id = me;
  delete from public.guest_transfers where from_user = me;
  if coalesce(ph,'') <> '' then delete from public.sms_outbox where right(phone, 10) = ph; end if;

  begin
    delete from auth.users where id = me;
  exception when others then
    -- нет прав на auth.users — хотя бы отвязываем номер
    begin update auth.users set phone = null, phone_confirmed_at = null where id = me; exception when others then null; end;
  end;
  return jsonb_build_object('ok', true);
end $$;
