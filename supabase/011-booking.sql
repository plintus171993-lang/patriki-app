-- =====================================================================
--  Обновление 011: бронирование столов
--  • venues: booking_enabled, booking_deposit (₽ с человека, 0 — без депозита), booking_max_guests
--  • reservations — брони гостей; гость видит свои, управляющий — своего заведения
--  • place_reservation / cancel_reservation (гость), set_reservation_status (управляющий)
--  • новая бронь и отмена — в Telegram-тему заведения
--  Депозит: при booking_deposit > 0 бронь создаётся со статусом оплаты 'pending' и
--  подтверждается после оплаты (оплата депозита — следующим этапом, через ту же онлайн-оплату Сбера).
-- =====================================================================

alter table public.venues add column if not exists booking_enabled boolean not null default true;
alter table public.venues add column if not exists booking_deposit int not null default 0 check (booking_deposit >= 0);
alter table public.venues add column if not exists booking_max_guests int not null default 12 check (booking_max_guests between 1 and 100);

create table if not exists public.reservations (
  id             uuid primary key default gen_random_uuid(),
  number         bigint generated by default as identity (start with 501) unique,
  user_id        uuid default auth.uid(),
  venue_id       text not null references public.venues(id),
  starts_at      timestamptz not null,
  guests         int not null check (guests between 1 and 100),
  name           text not null,
  phone          text not null,
  comment        text not null default '',
  status         text not null default 'new' check (status in ('new','confirmed','declined','cancelled','done','noshow')),
  deposit        int not null default 0,
  payment_status text not null default 'none' check (payment_status in ('none','pending','held','paid','refunded','cancelled','failed')),
  staff_note     text not null default '',
  pd_consent_version text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists reservations_venue_time on public.reservations (venue_id, starts_at);
alter table public.reservations enable row level security;
drop policy if exists "reservations own read" on public.reservations;
create policy "reservations own read" on public.reservations for select to authenticated using (user_id = auth.uid());
drop policy if exists "reservations admin read" on public.reservations;
create policy "reservations admin read" on public.reservations for select to authenticated using (public.can_manage(venue_id));

-- менять поля брони денег может только владелец
create or replace function public.guard_venue_fields() returns trigger
language plpgsql as $$
begin
  if current_user in ('authenticated', 'anon') and not public.is_owner() and (
       new.name is distinct from old.name or new.address is distinct from old.address or new.zone is distinct from old.zone or
       new.delivery_fee is distinct from old.delivery_fee or new.min_order is distinct from old.min_order or
       new.pay_online is distinct from old.pay_online or new.booking_deposit is distinct from old.booking_deposit or
       new.id is distinct from old.id) then
    raise exception 'Эти настройки меняет только владелец';
  end if;
  return new;
end $$;

create or replace function public.reservation_tg_text(r public.reservations, p_head text) returns text
language sql stable security definer set search_path = public as $$
  select format(E'%s №%s\n📍 %s\n🗓 %s\n👥 %s чел.\n%s, %s%s%s',
    p_head, r.number, upper(coalesce((select name from public.venues where id = r.venue_id), r.venue_id)),
    to_char(r.starts_at at time zone 'Europe/Moscow', 'DD.MM.YYYY, HH24:MI'), r.guests, r.name, r.phone,
    case when r.comment <> '' then E'\nКомментарий: ' || r.comment else '' end,
    case when r.deposit > 0 then format(E'\nДепозит: %s ₽ (%s)', r.deposit, r.payment_status) else '' end);
$$;

create or replace function public.reservation_notify(r public.reservations, p_head text) returns void
language plpgsql security definer set search_path = public as $$
declare venue_chat text; owner_chat text; msg text;
begin
  select value into venue_chat from public.app_secrets where key = 'telegram_chat_id:' || r.venue_id;
  select value into owner_chat from public.app_secrets where key = 'telegram_chat_id';
  msg := public.reservation_tg_text(r, p_head);
  if venue_chat is not null then perform public.tg_send(venue_chat, msg); end if;
  if owner_chat is not null and owner_chat is distinct from venue_chat then perform public.tg_send(owner_chat, msg); end if;
exception when others then null;
end $$;

-- бронь от гостя
create or replace function public.place_reservation(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v public.venues; r public.reservations; ts timestamptz; g int; ph text; nm text;
begin
  if auth.uid() is null then raise exception 'Нет входа'; end if;
  if coalesce((p->>'pd_consent')::boolean, false) is not true then raise exception 'Нужно согласие на обработку персональных данных'; end if;
  select * into v from public.venues where id = p->>'venue_id';
  if not found then raise exception 'Заведение не найдено'; end if;
  if not v.booking_enabled or v.accepting = false then raise exception 'Бронирование в этом заведении пока недоступно'; end if;
  ts := (p->>'starts_at')::timestamptz;
  if ts is null or ts < now() + interval '30 minutes' then raise exception 'Выберите время хотя бы через 30 минут'; end if;
  if ts > now() + interval '60 days' then raise exception 'Бронь — не дальше чем на 60 дней вперёд'; end if;
  g := coalesce((p->>'guests')::int, 0);
  if g < 1 or g > v.booking_max_guests then raise exception 'Гостей: от 1 до %. Для большой компании позвоните в паб', v.booking_max_guests; end if;
  nm := left(trim(coalesce(p->>'name', '')), 80);
  ph := regexp_replace(coalesce(p->>'phone', ''), '\D', '', 'g');
  if nm = '' then raise exception 'Укажите имя'; end if;
  if length(ph) < 11 then raise exception 'Укажите телефон'; end if;
  if (select count(*) from public.reservations where user_id = auth.uid() and status in ('new','confirmed') and starts_at > now()) >= 3 then
    raise exception 'У вас уже 3 активные брони. Отмените лишнюю или позвоните в паб';
  end if;
  insert into public.reservations (venue_id, starts_at, guests, name, phone, comment, deposit, payment_status, pd_consent_version)
  values (v.id, ts, g, nm, '+' || ph, left(coalesce(p->>'comment', ''), 300),
          v.booking_deposit * g, case when v.booking_deposit > 0 then 'pending' else 'none' end, p->>'pd_consent_version')
  returning * into r;
  if r.deposit = 0 then perform public.reservation_notify(r, '🍺 Новая бронь'); end if;   -- с депозитом — после оплаты
  return jsonb_build_object('id', r.id, 'number', r.number, 'deposit', r.deposit, 'status', r.status, 'payment_status', r.payment_status);
end $$;

create or replace function public.cancel_reservation(p_id uuid) returns void
language plpgsql security definer set search_path = public as $$
declare r public.reservations;
begin
  select * into r from public.reservations where id = p_id and user_id = auth.uid() for update;
  if not found then raise exception 'Бронь не найдена'; end if;
  if r.status not in ('new','confirmed') then raise exception 'Эту бронь уже нельзя отменить'; end if;
  update public.reservations set status = 'cancelled', updated_at = now() where id = p_id returning * into r;
  perform public.reservation_notify(r, '❌ Гость отменил бронь');
end $$;

create or replace function public.set_reservation_status(p_id uuid, p_status text, p_note text default '') returns void
language plpgsql security definer set search_path = public as $$
declare r public.reservations;
begin
  select * into r from public.reservations where id = p_id for update;
  if not found then raise exception 'Бронь не найдена'; end if;
  if not public.can_manage(r.venue_id) then raise exception 'Нет прав'; end if;
  if p_status not in ('confirmed','declined','done','noshow','cancelled') then raise exception 'Неверный статус'; end if;
  update public.reservations set status = p_status, staff_note = coalesce(nullif(p_note, ''), staff_note), updated_at = now() where id = p_id;
end $$;

grant execute on function public.place_reservation(jsonb), public.cancel_reservation(uuid), public.set_reservation_status(uuid, text, text) to authenticated;
revoke execute on function public.reservation_notify(public.reservations, text) from public, anon, authenticated;
